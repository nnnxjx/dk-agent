'',
'## 结论与限制',
'',
'本轮建立更大文档题库的开发基线，不将其与旧合成题库成绩直接相减来宣称算法提升。关闭重排的对照需在同一语料、问题及 TopK 下另跑；本轮摘要默认只描述启用重排的运行。',
'',
'原第一至三步数据与无答案场景不改。本轮不评估无答案拒答、知识库外问题、PDF 解析或并发负载；检索和问答可能并行运行，顺序请求耗时不代表生产 SLA。生成 Token 与成本不可用。下一步先审核标签及失败样例，再决定优化；保留测试集留到方案冻结后执行。',
