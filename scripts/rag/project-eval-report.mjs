'',
'本地报告目录被 Git 忽略，代码提交不包含这些 JSON；本文与题库可随代码追踪。单题检索为 `retrieval-project-XXX-kK.json`，单题回答为 `answers-project-XXX.json`；后者包含事件、工具参数、实际片段、回答、原始和引文校验后的判断。',
'',
'## 检索阶段',
