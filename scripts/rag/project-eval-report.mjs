#!/usr/bin/env node
// 将本地报告整理为仓库内可追踪的中文摘要；不调用模型、不修改知识库。
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { loadDataset, readJson } from './project-eval-lib.mjs';
const dir=resolve(process.argv[2] || 'reports/rag-baseline/project-step4-v1');
const data=await loadDataset();
const retrieval=await readJson(resolve(dir,'dev-retrieval-summary.json'));
const answers=await readJson(resolve(dir,'dev-answers-summary.json'));
const binding=await readJson(resolve(dir,'binding.json'));
